//! Topology queries and history: what a shape is made of and where its faces came from.
//!
//! Entities are identified by their index in the backend's enumeration of the shape. The
//! enumeration is deterministic for a given shape (determinism tier T1) and survives a cache
//! round trip, but its numbering is **not** part of the format: persistent names (spec/naming.md)
//! are built from [`Lineage`], never from indices.

use crate::geometry::V3;

/// The kind of surface under a face.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum SurfaceKind {
    /// Flat.
    Plane,
    /// Right circular cylinder.
    Cylinder,
    /// Right circular cone.
    Cone,
    /// Sphere.
    Sphere,
    /// Torus.
    Torus,
    /// Any other surface (B-spline, extrusion, revolution, offset, ...).
    BSpline,
}

impl SurfaceKind {
    /// The word used in `type=` filters.
    pub fn word(self) -> &'static str {
        match self {
            SurfaceKind::Plane => "plane",
            SurfaceKind::Cylinder => "cylinder",
            SurfaceKind::Cone => "cone",
            SurfaceKind::Sphere => "sphere",
            SurfaceKind::Torus => "torus",
            SurfaceKind::BSpline => "bspline",
        }
    }
}

/// One face of a shape.
#[derive(Clone, Debug, PartialEq)]
pub struct FaceInfo {
    /// Surface kind.
    pub kind: SurfaceKind,
    /// Outward unit normal of a planar face (taking the face orientation into account).
    pub normal: Option<V3>,
    /// Axis of a cylinder, cone or torus: a point on it and the unit direction.
    pub axis: Option<(V3, V3)>,
    /// Radius of a cylinder, sphere or torus (major), or the reference radius of a cone.
    pub radius: Option<f64>,
    /// Center of mass of the face (mm).
    pub centroid: V3,
    /// Area (mm^2).
    pub area: f64,
    /// Indices of the bounding edges.
    pub edges: Vec<u32>,
}

/// The kind of curve under an edge.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum CurveKind {
    /// Straight.
    Line,
    /// Circle or circular arc.
    Circle,
    /// Ellipse or elliptic arc.
    Ellipse,
    /// Any other curve.
    BSpline,
}

/// One edge of a shape.
#[derive(Clone, Debug, PartialEq)]
pub struct EdgeInfo {
    /// Curve kind.
    pub kind: CurveKind,
    /// Start and end points.
    pub ends: (V3, V3),
    /// Point halfway along the curve.
    pub midpoint: V3,
    /// Length (mm).
    pub length: f64,
    /// Radius of a circular edge.
    pub radius: Option<f64>,
    /// Unit direction of a straight edge.
    pub direction: Option<V3>,
    /// Indices of the faces that share the edge (one or two for a solid).
    pub faces: Vec<u32>,
}

/// All faces and edges of a shape.
#[derive(Clone, Debug, Default, PartialEq)]
pub struct TopoInfo {
    /// Faces, by index.
    pub faces: Vec<FaceInfo>,
    /// Edges, by index.
    pub edges: Vec<EdgeInfo>,
}

/// The role a face was created in by the operation that made it.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Role {
    /// The cap at the start of an extrusion, revolution, sweep or loft (the profile itself).
    CapStart,
    /// The cap at the end.
    CapEnd,
    /// The side generated by segment `seg` of loop `lp` of the profile (loft: of the first section).
    Side {
        /// Loop index (0 is the outer loop).
        lp: u32,
        /// Segment index within the loop.
        seg: u32,
    },
    /// A face generated from an edge of the input shape (a fillet or chamfer surface, the rim
    /// of a shell). The number is the input edge index.
    FromEdge(u32),
    /// A face generated from a face of the input shape (the inner wall of a shell). The number
    /// is the input face index.
    FromFace(u32),
}

/// Where a face of the result came from.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct Lineage {
    /// `(result face, operand, input face)`: the result face is the input face (possibly trimmed,
    /// split or merged with others). `operand` is 0 for the first shape of the operation, 1 for the
    /// second. A result face may appear several times (merged faces) and an input face may appear
    /// several times (split faces).
    pub inherited: Vec<(u32, u8, u32)>,
    /// `(result face, role)`: faces the operation created.
    pub created: Vec<(u32, Role)>,
}
